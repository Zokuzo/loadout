#!/usr/bin/env python3
"""Writes flow/hooks/atlas.ts: the bubble map's letters, as pixels.

The mod has no font engine, so each letter it can draw is rasterised here, once, and committed as data.
JetBrains Mono (SIL Open Font License 1.1, see flow/hooks/atlas-OFL.txt), Medium and ExtraBold, at the
four pitches the bubble map uses. A pitch is how many pixels each letter advances.

Run it again only to change the letters: python3 flow/tools/atlas.py   (needs Pillow and the font files)
"""
import base64, glob, math, os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'hooks', 'atlas.ts')
# name -> (pitch, weight): the five faces the bubble map writes with
FACES = {'6b': (6, 'ExtraBold'), '7': (7, 'Medium'), '7b': (7, 'ExtraBold'), '8b': (8, 'ExtraBold'), '9b': (9, 'ExtraBold')}
# ASCII, the Latin-1 letters and signs, and the few marks a call or a name may hold beyond them
CHARS = ''.join(chr(c) for c in [*range(32, 127), *range(161, 256)]) + '…’‘“”–—→←œŒ€✓✗'
PAD = 2  # pixels kept around a letter's slot, on all four sides: a heavy letter leans out, a ring rises above


def font_file(weight):
    found = glob.glob(f'/usr/share/fonts/**/JetBrainsMono-{weight}.ttf', recursive=True)
    if not found: sys.exit(f'JetBrainsMono-{weight}.ttf is not installed')
    return found[0]


def face(pitch, weight):
    """The font sized so one letter advances exactly `pitch` pixels."""
    probe = ImageFont.truetype(font_file(weight), 100)
    return ImageFont.truetype(font_file(weight), pitch * 100 / probe.getlength('M'))


def glyphs(pitch, weight):
    """(height, coverage bytes): one cell of (pitch + 2 PAD) x (height + 2 PAD) per letter of CHARS, 0..255 a pixel."""
    font = face(pitch, weight)
    ascent, descent = font.getmetrics()
    height = math.ceil(ascent + descent)
    width, tall = pitch + 2 * PAD, height + 2 * PAD
    out = bytearray()
    for ch in CHARS:
        cell = Image.new('L', (width, tall), 0)
        # a letter the font lacks is drawn as its "missing" box: better seen than dropped
        ImageDraw.Draw(cell).text((PAD, PAD), ch, font=font, fill=255)
        wide = Image.new('L', (width + 8, tall + 8), 0)
        ImageDraw.Draw(wide).text((PAD + 4, PAD + 4), ch, font=font, fill=255)
        box = wide.getbbox()
        assert box is None or (box[0] >= 4 and box[1] >= 4 and box[2] <= width + 4 and box[3] <= tall + 4), f'{ch!r} at {pitch} {weight} leaves its cell: {box}'
        out += cell.tobytes()
    return height, bytes(out)


def main():
    lines = [
        '// GENERATED by flow/tools/atlas.py: do not edit. The letters of the bubble map, as pixels.',
        '// JetBrains Mono, Copyright 2020 The JetBrains Mono Project Authors, SIL Open Font License 1.1 (atlas-OFL.txt).',
        '',
        '/** Every letter a face holds, in the order of its cells. */',
        f'export const CHARS = {CHARS!r}' if "'" not in CHARS and '\\' not in CHARS else 'export const CHARS = ' + '"' + CHARS.replace('\\', '\\\\').replace('"', '\\"') + '"',
        '',
        '/** Pixels kept around a letter\'s slot, on all four sides. */',
        f'export const PAD = {PAD}',
        '',
        '/** A face: `pitch` pixels a letter, cells of (pitch + 2 PAD) x (height + 2 PAD), one coverage byte a pixel, base64. */',
        'export const FACES: Record<string, { pitch: number; height: number; cells: string }> = {',
    ]
    for name, (pitch, weight) in FACES.items():
        height, data = glyphs(pitch, weight)
        lines.append(f"  '{name}': {{ pitch: {pitch}, height: {height}, cells: '{base64.b64encode(data).decode()}' }},")
    lines += ['}', '']
    with open(OUT, 'w', encoding='utf-8') as f: f.write('\n'.join(lines))
    print(f'{OUT}: {len(CHARS)} letters x {len(FACES)} faces, {os.path.getsize(OUT) // 1024} KB')


if __name__ == '__main__':
    main()
