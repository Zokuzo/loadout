export type FormSprite = { name: string; frames: readonly (readonly (number | null)[])[][] }

export const decode = (palette: readonly number[], frames: readonly (readonly string[])[]) =>
  frames.map(rows => rows.map(row => [...row].map(ch => (ch === '.' ? null : palette[INK.indexOf(ch)] ?? null))))

